#!/usr/bin/env python3
"""Reproduce the pinned, offline lunar engine; run only when updating the vendor."""
import hashlib
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
REVISION = '4c45a59f79b856125516f31aefa8295035c16afd'
SHA256 = '9750324bfe1aa63c146f8c72b1143df924466c11c8a5277d7d9225c541a18aaa'
BASE = f'https://raw.githubusercontent.com/6tail/lunar-javascript/{REVISION}/'


def build(source, license_text):
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError('Unexpected upstream lunar.js checksum')
    body = source.decode('utf-8').split('})(this,function(){', 1)[1].strip()
    assert body.endswith('});')
    header = f'// SPDX-License-Identifier: MIT\n// lunar-javascript 1.7.7, {REVISION}\n// Generated by scripts/update-lunar-vendor.py; only the UMD wrapper is replaced.\n'
    return header + '/*\n' + license_text.strip() + '\n*/\nexport const lunarEngine = (() => {\n' + body[:-3] + '})();\n'


if __name__ == '__main__':
    source = urlopen(BASE + 'lunar.js', timeout=30).read()
    license_text = urlopen(BASE + 'LICENSE', timeout=30).read().decode('utf-8')
    (ROOT / 'src/lunar-engine.js').write_text(build(source, license_text), encoding='utf-8', newline='\n')
    print('Vendored lunar-javascript 1.7.7 with the complete MIT license.')
