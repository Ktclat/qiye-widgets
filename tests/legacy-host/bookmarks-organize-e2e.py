#!/usr/bin/env python3
"""Mouse dragging, compact toolbar and batch management with disposable data."""
import argparse, copy, json, os, subprocess, threading
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(); parser.add_argument('--preview',action='store_true'); args=parser.parse_args()
OUT=ROOT/'output/playwright/bookmarks'; OUT.mkdir(parents=True,exist_ok=True)
seed=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {DEFAULT_STATE} from './src/core.js';console.log(JSON.stringify(DEFAULT_STATE))"],cwd=ROOT))
seed['settings'].update(language='zh-CN',autoExtractIcons=False)
def node(id,parent='',url=None): return dict(id=id,parentId=parent,title={'work':'工作资料','archive':'归档','nested':'子文件夹','design':'设计规范'}.get(id,id),url=url,dateAdded=1)
entries=[node('work'),node('archive'),node('nested','work'),node('design','nested','https://design.example/'),node('MDN','','https://developer.mozilla.org/'),node('GitHub','','https://github.com/'),node('W3C','','https://w3.org/')]
seed['items']=[dict(id='bookmarks-test',groupId=seed['activeGroupId'],type='widget',widget='bookmarks',title='书签',size='4x2',config={'source':'local'},data={'nodes':entries})]
checks=[]
def check(name,value=True):
    assert value,name
    checks.append(name); print('PASS',name,flush=True)
class Quiet(SimpleHTTPRequestHandler):
    def log_message(self,*args): pass
server=ThreadingHTTPServer(('127.0.0.1',0),partial(Quiet,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start()
base=f'http://127.0.0.1:{server.server_port}/'+('Qiye-preview.html' if args.preview else '')
with sync_playwright() as p:
    browser=p.chromium.launch(**({'executable_path':os.environ['CHROMIUM_PATH']} if os.environ.get('CHROMIUM_PATH') else {}))
    context=browser.new_context(viewport={'width':1440,'height':950}); page=context.new_page(); page.set_default_timeout(8000)
    errors=[]; page.on('pageerror',lambda e:errors.append(str(e)))
    page.route('https://**/*',lambda route:route.abort())
    page.add_init_script('if(!localStorage.getItem("qiye.state.v5")) localStorage.setItem("qiye.state.v5",'+json.dumps(json.dumps(seed,ensure_ascii=False))+');')
    page.add_init_script((ROOT/'tests/bookmarks-browser-fixture.js').read_text(encoding='utf-8'))
    def data(): return page.evaluate('JSON.parse(localStorage.getItem("qiye.state.v5")).items[0].data.nodes')
    def parent(id): return next(n['parentId'] for n in data() if n['id']==id)
    def row(id): return page.locator('[data-bm-row="'+id+'"]')
    def tree(id): return page.locator('.bm-tree [data-bm-folder="'+id+'"]')
    def pick(id,sidebar=False): page.locator(('.bm-sidebar' if sidebar else '.bm-list')+' [data-bm-select="'+id+'"]').check()
    def submit(): page.locator('#bm-editor-form button[type=submit]').click()
    def drag(source,target,position='inside'):
        expect(source).to_be_visible(); expect(target).to_be_visible(); page.wait_for_timeout(250)
        a=source.bounding_box(); b=target.bounding_box()
        x=a['x']+min(a['width']/2,90); y=a['y']+a['height']/2
        tx=b['x']+min(b['width']/2,80); ty=b['y']+(4 if position=='before' else b['height']-4 if position=='after' else b['height']/2)
        page.mouse.move(x,y); page.mouse.down(); page.mouse.move(x+8,y+5,steps=5); page.mouse.move(tx,ty,steps=15); page.mouse.move(tx,ty,steps=2); page.mouse.up()
        page.wait_for_timeout(200)
    def open_manager():
        page.locator('[data-widget=bookmarks] [data-action=widget-open]').first.click(); page.wait_for_timeout(300)
    try:
        page.goto(base,wait_until='domcontentloaded'); open_manager()
        check('recent navigation and content banner are removed',page.locator('[data-bm-action=recent],.bm-heading,.bm-toolbar').count()==0)
        check('first bookmark row starts directly under the 48px header',page.locator('.bookmarks-app').evaluate('n=>n.querySelector("[data-bm-row]").getBoundingClientRect().y-n.querySelector(".bm-header").getBoundingClientRect().y<=49'))
        check('all create edit and sorting controls live inside the header',page.locator('.bm-header [data-bm-action=new-folder],.bm-header [data-bm-action=new-bookmark],.bm-header [data-bm-action=edit],.bm-header [data-bm-sort]').count()==4)
        drag(row('MDN'),row('W3C'),'before')
        check('mouse drag reorders downward', [n['id'] for n in data() if n['parentId']==''] == ['work','archive','GitHub','MDN','W3C'])
        drag(row('W3C'),row('GitHub'),'before')
        check('mouse drag reorders upward', [n['id'] for n in data() if n['parentId']==''] == ['work','archive','W3C','GitHub','MDN'])
        drag(row('MDN'),tree('archive'))
        check('mouse drag moves a bookmark into a sidebar folder',parent('MDN')=='archive')
        tree('archive').click(); page.wait_for_timeout(150)
        a=row('MDN').bounding_box(); b=page.locator('.bm-path summary').bounding_box()
        page.mouse.move(a['x']+80,a['y']+a['height']/2); page.mouse.down(); page.mouse.move(a['x']+90,a['y']+a['height']/2,steps=5)
        page.mouse.move(b['x']+15,b['y']+15,steps=15); expect(page.locator('.bm-breadcrumb')).to_be_visible()
        dest=page.locator('.bm-breadcrumb [data-bm-folder=""]').bounding_box()
        page.mouse.move(dest['x']+30,dest['y']+15,steps=10); page.mouse.move(dest['x']+30,dest['y']+15); page.mouse.up(); page.wait_for_timeout(200)
        check('hovering the titlebar path exposes ancestor drop targets',parent('MDN')=='')
        tree('').click(); drag(row('MDN'),tree('archive'))
        page.locator('[data-bm-toggle="work"]').click()
        before=copy.deepcopy(data()); drag(row('work'),tree('nested'))
        check('dragging a folder into a descendant is refused',data()==before)
        page.locator('.bm-list').evaluate("n=>{const d=new DataTransfer();d.setData('application/x-qiye-bookmarks','GitHub');n.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:d}))}")
        check('external drag payloads cannot mutate bookmarks',data()==before)
        page.locator('[data-bm-action=manage]').click(); pick('work'); pick('nested',True); pick('W3C')
        check('manage shows folder and bookmark checkboxes in both panes',page.locator('.bm-sidebar [data-bm-select]').count()==3 and page.locator('.bm-list [data-bm-select]').count()==4)
        page.locator('[data-bm-action=batch-move]').click()
        check('batch picker excludes all selected folder descendants',page.locator('[name=parentId] option[value="work"],[name=parentId] option[value="nested"]').count()==0)
        expect(page.locator('.bm-editor')).to_contain_text('移动所选的 2 项')
        page.locator('[name=parentId]').select_option('archive'); submit(); expect(page.locator('.bm-editor-overlay')).to_be_hidden()
        check('parent and child selection is moved only once',parent('work')=='archive' and parent('nested')=='work' and parent('W3C')=='archive')
        pick('MDN'); pick('W3C'); before=copy.deepcopy(data())
        page.locator('[data-bm-action=batch-delete]').click(); page.keyboard.press('Escape')
        check('cancelled batch delete retains all data and selection',data()==before and page.locator('.bm-selection-count').inner_text()=='2')
        page.locator('[data-bm-action=batch-move]').click(); page.locator('[name=parentId]').select_option('')
        page.evaluate("()=>{const set=Storage.prototype.setItem;let fail=true;Storage.prototype.setItem=function(k,v){if(k==='qiye.state.v5'&&fail){fail=false;throw new Error('batch storage failure')}return set.call(this,k,v)}}")
        submit(); expect(page.locator('.bm-editor-feedback')).to_contain_text('batch storage failure')
        check('failed local batch writes nothing and retains selection',data()==before and page.locator('.bm-selection-count').inner_text()=='2')
        submit(); expect(page.locator('.bm-editor-overlay')).to_be_hidden()
        check('local batch retry persists both items',parent('MDN')=='' and parent('W3C')=='')
        pick('MDN'); pick('W3C'); drag(row('MDN'),tree('work'))
        check('dragging a selection moves all selected roots',parent('MDN')=='work' and parent('W3C')=='work')
        tree('archive').click(); pick('work'); pick('nested',True)
        page.locator('[data-bm-action=batch-delete]').click()
        expect(page.locator('.bm-editor')).to_contain_text('3 个书签和 2 个文件夹')
        submit(); expect(page.locator('.bm-editor-overlay')).to_be_hidden()
        check('batch recursive delete removes the reviewed subtree only',[n['id'] for n in data()]==['archive','GitHub'])
        page.locator('[data-close]').click(); page.reload(); open_manager()
        check('drag order and batch changes survive reload',[n['id'] for n in data()]==['archive','GitHub'])
        page.evaluate('__bookmarkTest.acceptRequest=true'); page.locator('.bm-source-switch summary').click(); page.locator('[data-bm-source=browser]').click()
        expect(page.locator('[data-bm-source=browser]')).to_have_attribute('aria-pressed','true')
        page.locator('[data-bm-action=manage]').click()
        check('native system and managed items cannot be selected',page.locator('.bm-list [data-bm-select]:disabled').count()==3)
        tree('1').click(); tree('10').click(); pick('11'); pick('12')
        page.evaluate('__bookmarkTest.failAfter=1')
        page.locator('[data-bm-action=batch-move]').click(); page.locator('[name=parentId]').select_option('2'); submit()
        expect(page.locator('.bm-editor-overlay')).to_be_hidden(); expect(page.locator('.bm-feedback')).to_contain_text('已完成 1 项')
        check('native partial failure keeps uncompleted items selected',page.locator('.bm-selection-count').inner_text()=='1' and page.evaluate('__bookmarkTest.nodes.find(n=>n.id==="11").parentId')=='2' and page.evaluate('__bookmarkTest.nodes.find(n=>n.id==="12").parentId')=='10')
        page.evaluate('__bookmarkTest.failAfter=-1'); page.locator('[data-bm-action=batch-move]').click(); page.locator('[name=parentId]').select_option('2'); submit(); expect(page.locator('.bm-editor-overlay')).to_be_hidden()
        check('retry acts only on remaining native items',page.evaluate('__bookmarkTest.nodes.find(n=>n.id==="12").parentId')=='2')
        drag(row('12'),row('11'),'before')
        check('native mouse reorder passes the browser index',page.evaluate('__bookmarkTest.calls.filter(c=>c[0]==="move").at(-1)[2].index')==0)
        a=row('11').bounding_box(); page.mouse.move(a['x']+80,a['y']+15); page.mouse.down(); page.mouse.move(a['x']+90,a['y']+20,steps=5)
        page.evaluate("__bookmarkTest.nodes.push({id:'during-drag',parentId:'2',title:'Changed during drag',url:'https://during.example/'});chrome.bookmarks.onCreated.emit('during-drag',{})")
        page.wait_for_timeout(120); page.mouse.move(10,10,steps=15); page.mouse.up()
        expect(page.locator('.bm-list')).to_contain_text('Changed during drag')
        check('native changes during a cancelled drag refresh afterwards')
        page.evaluate("__bookmarkTest.nodes=__bookmarkTest.nodes.filter(n=>n.id!=='during-drag');chrome.bookmarks.onRemoved.emit('during-drag',{})")
        expect(page.locator('[data-bm-row="during-drag"]')).to_have_count(0)
        page.locator('[data-bm-action=manage]').click()
        page.locator('.bm-sort summary').click(); page.locator('[data-bm-sort]').select_option('title'); page.keyboard.press('Escape')
        before=page.evaluate('JSON.stringify(__bookmarkTest.nodes)'); drag(row('11'),row('12'),'before')
        check('sorted views do not silently overwrite manual order',page.evaluate('JSON.stringify(__bookmarkTest.nodes)')==before)
        page.locator('.bm-path summary').click(); expect(page.locator('.bm-breadcrumb')).to_contain_text('其他书签'); page.keyboard.press('Escape')
        check('titlebar path exposes all ancestors without a content banner')
        page.locator('[data-bm-action=manage]').click(); page.locator('[data-bm-select-all]').check()
        check('select all selects current results',page.locator('.bm-selection-count').inner_text()=='2')
        page.screenshot(path=str(OUT/('organize-preview-dark.png' if args.preview else 'organize-dark.png')))
        page.evaluate('document.documentElement.dataset.theme="light"'); page.screenshot(path=str(OUT/('organize-preview-light.png' if args.preview else 'organize-light.png')))
        page.set_viewport_size({'width':390,'height':844})
        # The app updates window sizing in its asynchronous resize handler.
        page.wait_for_function('''()=>{const dialog=document.querySelector('#dialog'),header=document.querySelector('.bm-header');
          return dialog.getBoundingClientRect().width<=innerWidth-24&&header.offsetHeight===44&&header.scrollWidth<=header.clientWidth;}''')
        check('narrow management toolbar remains one 44px row',page.locator('.bm-header').evaluate('n=>n.offsetHeight===44 && n.scrollWidth<=n.clientWidth'))
        for action in ['batch-move','batch-delete','manage']: expect(page.locator('[data-bm-action='+action+']')).to_be_in_viewport()
        page.screenshot(path=str(OUT/('organize-preview-narrow.png' if args.preview else 'organize-narrow.png')))
        page.keyboard.press('Control+f'); expect(page.locator('[data-bm-query]')).to_be_focused(); page.locator('[data-bm-query]').fill('Browser'); expect(page.locator('.bm-list')).to_contain_text('Browser guide')
        check('narrow management keeps keyboard search usable')
        page.keyboard.press('Escape'); page.set_viewport_size({'width':360,'height':780})
        page.wait_for_function('''()=>{const dialog=document.querySelector('#dialog'),header=document.querySelector('.bm-header');
          return dialog.getBoundingClientRect().width<=innerWidth-24&&header.scrollWidth<=header.clientWidth;}''')
        check('360px management does not overflow',page.locator('.bm-header').evaluate('n=>n.scrollWidth<=n.clientWidth'))
        check('no uncaught JavaScript errors',not errors)
    except Exception:
        page.screenshot(path=str(OUT/'organize-failure.png')); raise
    finally:
        (OUT/('organize-preview-report.json' if args.preview else 'organize-report.json')).write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
        context.close(); browser.close(); server.shutdown()
print(f'{len(checks)} organization checks passed.')
