#!/usr/bin/env python3
"""Encoding workspace regression on production modules or the standalone preview."""
import argparse
import copy
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import json
import os
from pathlib import Path
import subprocess
import threading
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--preview', action='store_true')
args = parser.parse_args()
OUT = ROOT / 'output/playwright/codec'
OUT.mkdir(parents=True, exist_ok=True)
state0 = json.loads(subprocess.check_output(['node', '--input-type=module', '-e', "import {DEFAULT_STATE} from './src/core.js';console.log(JSON.stringify(DEFAULT_STATE))"], cwd=ROOT))
checks = []


def check(name, condition):
    assert condition, name
    checks.append(name)
    print('PASS', name, flush=True)


class Quiet(SimpleHTTPRequestHandler):
    def log_message(self, *args): pass


server = ThreadingHTTPServer(('127.0.0.1', 0), partial(Quiet, directory=str(ROOT)))
threading.Thread(target=server.serve_forever, daemon=True).start()
base = f'http://127.0.0.1:{server.server_port}/' + ('Qiye-preview.html' if args.preview else '')
suffix = '-preview' if args.preview else ''
with sync_playwright() as p:
    executable = os.environ.get('CHROMIUM_PATH')
    browser = p.chromium.launch(**({'executable_path': executable} if executable else {}))
    try:
        for language, theme in [('zh-CN', 'light'), ('en', 'dark')]:
            state = copy.deepcopy(state0)
            state['items'] = []
            state['settings'].update(language=language, theme=theme, autoExtractIcons=False)
            context = browser.new_context(viewport={'width':1440,'height':960}, permissions=['clipboard-read','clipboard-write'])
            page = context.new_page()
            page.set_default_timeout(10000)
            errors, network = [], []
            page.on('pageerror', lambda error: errors.append(str(error)))
            page.on('console', lambda message: print('CONSOLE', message.text, flush=True) if message.type=='error' and 'Qiye' in message.text else None)
            page.on('request', lambda request: network.append(request.url))
            page.route('https://**/*', lambda route: route.abort())
            payload = json.dumps(state, ensure_ascii=False)
            page.add_init_script('if(!localStorage.getItem("qiye.state.v5"))localStorage.setItem("qiye.state.v5",'+json.dumps(payload)+')')
            page.goto(base, wait_until='domcontentloaded')
            page.locator('#groups [data-group]').first.wait_for()
            page.locator('.top-tools [data-action=add]').click()
            page.locator('[data-add-tab=widgets]').click()
            for term in (['佛曰','兽语','与熊论道'] if language == 'zh-CN' else ['Buddha','Beast','Bear']):
                page.locator('#widget-query').fill(term)
                check(f'{language} discoverable by {term}', page.locator('[data-catalog-widget=codec]').is_visible())
            page.locator('#widget-query').fill('Base64')
            check(f'{language} discoverable in catalog', page.locator('[data-catalog-widget=codec]').is_visible())
            page.locator('[data-add-widget=codec]').click()
            page.wait_for_function('document.querySelector("[data-add-feedback]")?.textContent.length > 0')
            check(f'{language} catalog remains open after adding', page.locator('#dialog').is_visible())
            page.locator('#dialog [data-close]').click()
            page.locator('#dialog').wait_for(state='hidden')
            page.locator('#desktop [data-widget=codec] [data-codec-algorithm=base64]').click()
            source, result = page.locator('#codec-input'), page.locator('#codec-output')

            def expected(value):
                page.wait_for_function('(value)=>document.querySelector("#codec-output").value===value', arg=value)

            def choose(algorithm):
                page.locator(f'.codec-nav [data-codec-algorithm="{algorithm}"]').click()

            def close():
                page.locator('#dialog [data-close]').click()
                page.locator('#dialog').wait_for(state='hidden')

            check(f'{language} input focused on open', source.evaluate('e=>e===document.activeElement'))
            start_network = len(network)
            text = '你好，Qiye 👋'
            source.fill(text)
            expected('5L2g5aW977yMUWl5ZSDwn5GL')
            check(f'{language} UTF-8 live conversion', result.input_value() == '5L2g5aW977yMUWl5ZSDwn5GL')
            page.locator('[data-codec-action=copy]').click()
            check(f'{language} copy writes exact result', page.evaluate('navigator.clipboard.readText()') == result.input_value())
            page.screenshot(path=str(OUT/f'workspace-{language}{suffix}.png'), animations='disabled')
            page.evaluate('''() => { window.originalCopy=navigator.clipboard.writeText.bind(navigator.clipboard); navigator.clipboard.writeText=async()=>{throw new Error('Permission denied');}; }''')
            page.locator('[data-codec-action=copy]').click()
            check(f'{language} denied clipboard selects result for manual copy', result.evaluate('e=>document.activeElement===e && e.selectionStart===0 && e.selectionEnd===e.value.length'))
            page.evaluate('() => {navigator.clipboard.writeText=window.originalCopy;}')
            page.locator('[data-codec-action=reuse]').click()
            page.locator('[data-codec-direction=decode]').click()
            expected(text)
            source.fill('%%%')
            page.wait_for_function('document.querySelector("#codec-input").getAttribute("aria-invalid")==="true"')
            check(f'{language} invalid input clears stale output', result.input_value()=='' and page.locator('[data-codec-action=copy]').is_disabled())
            page.locator('[data-codec-action=example]').click()
            expected(text)
            choose('url')
            source.fill('a+b%2Bc')
            expected('a+b+c')
            page.locator('[data-codec-url-mode]').select_option('form')
            expected('a b+c')
            choose('md2')
            source.fill('abc')
            expected('da853b0d3f88d99b30283a69e6ded6bb')
            check(f'{language} hashes have no decode action', not page.locator('[data-codec-direction=decode]').is_visible())
            page.locator('[data-codec-uppercase]').check()
            expected('DA853B0D3F88D99B30283A69E6DED6BB')
            page.locator('[data-codec-uppercase]').uncheck()
            choose('md4')
            expected('a448017aaf21d8525fc10ae87aa6729d')
            choose('md5')
            expected('900150983cd24fb0d6963f7d28e17f72')
            page.locator('[data-codec-action=clear]').click()
            page.locator('[data-codec-action=run]').click()
            expected('d41d8cd98f00b204e9800998ecf8427e')
            check(f'{language} empty text can be hashed', bool(result.input_value()))
            choose('sha-256')
            page.locator('[data-codec-auto]').uncheck()
            source.fill('abc')
            check(f'{language} manual mode invalidates old results', result.input_value()=='' and page.locator('[data-codec-action=copy]').is_disabled())
            source.press('Control+Enter')
            expected('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad')
            page.locator('[data-codec-auto]').check()
            page.evaluate('''() => { window.originalDigest = crypto.subtle.digest.bind(crypto.subtle); crypto.subtle.digest = (...args) => new Promise(resolve => { window.finishDigest = () => resolve(window.originalDigest(...args)); }); }''')
            source.fill('stale hash')
            page.wait_for_function('typeof window.finishDigest==="function"')
            choose('md5')
            source.fill('abc')
            expected('900150983cd24fb0d6963f7d28e17f72')
            page.evaluate('async () => { crypto.subtle.digest=window.originalDigest; await window.finishDigest(); }')
            check(f'{language} late SHA result cannot replace newer output', result.input_value()=='900150983cd24fb0d6963f7d28e17f72')
            choose('html')
            source.fill('&lt;img src=x onerror=alert(1)&gt;')
            expected('<img src=x onerror=alert(1)>')
            check(f'{language} decoded markup stays text', page.locator('.codec-main img').count()==0)
            choose('buddha')
            source.fill('佛曰：不呐佛故梵除梵蒙皤知奢數皤盧俱若諳度豆蒙娑故知孕他俱孕有呐孕奢礙冥逝姪罰那蒙顛佛冥夜依耶冥夢缽阿')
            expected('起来！不愿做奴隶的人们！')
            check(f'{language} classic Buddha fixture decodes', page.locator('[data-codec-fun-note]').is_visible())
            source.fill('佛又曰：不支持的格式')
            page.wait_for_function('document.querySelector("#codec-input").getAttribute("aria-invalid")==="true"')
            check(f'{language} unsupported Buddha variant has no stale result', result.input_value()=='' and page.locator('[data-codec-action=copy]').is_disabled())
            page.locator('[data-codec-direction=encode]').click()
            source.fill(text)
            page.wait_for_function('document.querySelector("#codec-output").value.startsWith("佛曰：")')
            page.screenshot(path=str(OUT/f'buddha-{language}{suffix}.png'), animations='disabled')
            page.locator('[data-codec-action=reuse]').click()
            page.locator('[data-codec-direction=decode]').click()
            expected(text)
            check(f'{language} Buddha handles Chinese and emoji', result.input_value()==text)
            choose('beast')
            page.locator('[data-codec-direction=encode]').click()
            source.fill('你好')
            beast_vector='~呜嗷呜嗷嗷嗷啊嗷嗷~啊呜~啊~呜呜嗷啊'
            expected(beast_vector)
            alphabet=page.locator('[data-codec-beast-alphabet]')
            alphabet.fill('喵呜咪~')
            expected(beast_vector.replace('嗷','喵').replace('啊','咪'))
            custom_beast=result.input_value()
            check(f'{language} custom Beast alphabet updates live', custom_beast.startswith('~呜喵'))
            check(f'{language} desktop playful controls fit without scrolling', page.locator('.codec-main').evaluate('e=>e.scrollHeight<=e.clientHeight+1'))
            page.screenshot(path=str(OUT/f'beast-{language}{suffix}.png'), animations='disabled')
            alphabet.fill('aaaa')
            page.wait_for_function('document.querySelector("#codec-input").getAttribute("aria-invalid")==="true"')
            check(f'{language} duplicate alphabet rejects without stale output', result.input_value()=='')
            page.locator('[data-codec-direction=decode]').click()
            source.fill(custom_beast)
            expected('你好')
            check(f'{language} Beast detects alphabet while decoding', not alphabet.is_visible())
            page.locator('[data-codec-action=example]').click()
            expected(text)
            check(f'{language} decode example ignores invalid hidden alphabet', result.input_value()==text)
            page.locator('[data-codec-direction=encode]').click()
            source.fill('你好')
            page.locator('[data-codec-action=reset-alphabet]').click()
            expected(beast_vector)
            check(f'{language} default Beast alphabet can be restored', alphabet.input_value()=='嗷呜啊~')
            choose('bear')
            source.fill(text)
            page.wait_for_function('document.querySelector("#codec-output").value.startsWith("熊曰：呋")')
            page.locator('[data-codec-action=reuse]').click()
            page.locator('[data-codec-direction=decode]').click()
            expected(text)
            check(f'{language} Bear roundtrip uses native compression', result.input_value()==text)
            source.fill('熊曰：呋既既現訴類常人囑蜂唬麼類嗥冬告告囑誒象取噗達唬哮類樣嗡萌嗄森物嗥出家蜜達嗒呆既吃溫唬哞咯襲拙告你嘿物人')
            expected('起来！不愿做奴隶的人们！')
            check(f'{language} original Bear fixture decodes', result.input_value()=='起来！不愿做奴隶的人们！')
            choose('base64')
            page.locator('[data-codec-direction=encode]').click()
            source.fill('a'*100001)
            page.wait_for_function('document.querySelector("#codec-input").getAttribute("aria-invalid")==="true"')
            check(f'{language} oversized input is rejected with actionable feedback', '100,000' in page.locator('#codec-status').inner_text() and result.input_value()=='')
            source.dispatch_event('compositionstart')
            source.fill('拼音')
            check(f'{language} composition does not publish partial output', result.input_value()=='')
            source.dispatch_event('compositionend')
            expected('5ou86Z+z')
            source.fill('private-codec-text')
            expected('cHJpdmF0ZS1jb2RlYy10ZXh0')
            check(f'{language} no text persisted', not page.evaluate('JSON.stringify({...localStorage,...sessionStorage}).includes("private-codec-text")'))
            check(f'{language} transforms do not request the network', len(network)==start_network)
            page.locator('[data-detail-action=window-expand]').click()
            check(f'{language} maximize retains input', source.input_value()=='private-codec-text')
            page.locator('[data-detail-action=window-expand]').click()
            close()
            page.locator('#desktop [data-widget=codec] [data-codec-algorithm=md5]').click()
            check(f'{language} reopening clears content and honors shortcut', source.input_value()=='' and page.locator('[data-codec-title]').inner_text()=='MD5')
            page.set_viewport_size({'width':360,'height':740})
            page.locator('[data-codec-select]').wait_for(state='visible')
            check(f'{language} narrow algorithm selector is available', page.locator('[data-codec-select]').is_visible())
            page.locator('[data-codec-select]').select_option('base64')
            source.fill(text)
            expected('5L2g5aW977yMUWl5ZSDwn5GL')
            check(f'{language} narrow layout has no horizontal overflow', page.locator('#dialog').evaluate('e=>e.scrollWidth<=e.clientWidth+1') and page.locator('.codec-main').evaluate('e=>e.scrollWidth<=e.clientWidth+1'))
            check(f'{language} narrow editor uses available width', source.bounding_box()['width']>280)
            page.screenshot(path=str(OUT/f'mobile-{language}{suffix}.png'), animations='disabled')
            page.locator('[data-codec-select]').select_option('beast')
            page.locator('[data-codec-direction=encode]').click()
            source.fill(text)
            page.wait_for_function('document.querySelector("#codec-output").value.startsWith("~呜嗷")')
            check(f'{language} narrow playful options fit', page.locator('.codec-main').evaluate('e=>e.scrollWidth<=e.clientWidth+1') and alphabet.input_value()=='嗷呜啊~')
            page.locator('.codec-main').evaluate('e=>e.scrollTop=0')
            page.screenshot(path=str(OUT/f'beast-mobile-{language}{suffix}.png'), animations='disabled')
            close()
            page.evaluate('''() => { const state=JSON.parse(localStorage.getItem('qiye.state.v5')); state.settings.windowSize=150; const item=state.items.find(i=>i.widget==='codec'); state.items=['1x1','1x2','2x1','2x2','4x2'].map((size,i)=>({...item,id:'codec-'+i,size})); localStorage.setItem('qiye.state.v5',JSON.stringify(state)); }''')
            page.reload()
            page.locator('#desktop [data-widget=codec]').first.wait_for()
            check(f'{language} five card sizes render', page.locator('#desktop [data-widget=codec]').count()==5)
            page.locator('#desktop [data-widget=codec] [data-action=widget-open]').first.click()
            check(f'{language} 360px viewport at 150% fits', page.locator('#dialog').evaluate('e=>e.scrollWidth<=e.clientWidth+1') and page.locator('.codec-main').evaluate('e=>e.scrollWidth<=e.clientWidth+1'))
            close()
            page.set_viewport_size({'width':1440,'height':960})
            # The viewport changes before the app's resize handler updates the grid.
            # Wait for desktop cell sizing before measuring caption/shortcut geometry.
            page.wait_for_function("expected=>parseFloat(document.documentElement.style.getPropertyValue('--cell-size'))===expected", arg=state0['settings']['gridSize'])
            check(f'{language} card captions do not overlap shortcuts', page.locator('#desktop .codec-card-hero').evaluate_all('nodes=>nodes.every(n=>n.lastElementChild.getBoundingClientRect().bottom<=n.nextElementSibling.getBoundingClientRect().top)'))
            page.screenshot(path=str(OUT/f'cards-{language}{suffix}.png'), animations='disabled')
            check(f'{language} no uncaught browser errors', not errors)
            context.close()
        (OUT/f'report{suffix}.json').write_text(json.dumps({'checks':checks,'passed':len(checks),'browser':browser.version},indent=2),encoding='utf-8')
    finally:
        browser.close()
        server.shutdown()
print(f'{len(checks)} codec checks passed.', flush=True)
